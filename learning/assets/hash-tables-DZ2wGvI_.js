  LL["linked list"] --> HT
  HT --> C["cache، مثل LRU"]
  HT --> DB["ایندکس پایگاه داده"]
  HT --> CP["کامپایلر: جدول نمادها"]
  HT --> NW["شبکه: جدول‌های مسیریاب و سوئیچ"]
  HT --> SEC["امنیت: hash های رمزنگاری"]
